using System.Globalization;
using System.Text;

using AstroCast.Core.Models;

namespace AstroCast.Core.Formatting;

/// <summary>
/// Formats <see cref="LunationSeries"/> and <see cref="LunationResult"/> data as Markdown.
/// </summary>
public static class LunationFormatter
{
    /// <summary>Invariant culture used for all numeric and date formatting.</summary>
    private static readonly CultureInfo Inv = CultureInfo.InvariantCulture;

    /// <summary>
    /// Format a lunation series as Markdown (timing table with eclipse indicators).
    /// </summary>
    /// <param name="series">The lunation series to format.</param>
    /// <returns>A Markdown-formatted lunation series report.</returns>
    public static string SeriesToMarkdown(LunationSeries series)
    {
        ArgumentNullException.ThrowIfNull(series);

        StringBuilder sb = new();

        sb.AppendLine(string.Create(Inv, $"# Lunations: {series.ScanStart.Year}") +
            (series.ScanStart.Year != series.ScanEnd.Year
                ? string.Create(Inv, $" \u2013 {series.ScanEnd.Year}")
                : ""));
        sb.AppendLine();
        sb.AppendLine(Inv, $"**Generated:** {series.CalculatedAt:yyyy-MM-dd HH:mm:ss} UTC  ");
        sb.AppendLine($"**Software:** {series.EngineVersion}  ");
        sb.AppendLine(Inv, $"**Period:** {series.ScanStart:yyyy-MM-dd} to {series.ScanEnd:yyyy-MM-dd}  ");
        if (series.Lunations.Count > 0 && CalendarDateFormatter.IsJulian(series.Lunations.Min(l => l.ExactUtc)))
            sb.AppendLine(CalendarDateFormatter.JulianCalendarLine + "  ");
        sb.AppendLine(Inv, $"**Lunations Found:** {series.Count} " +
            $"({series.NewMoons.Count} New Moons, {series.FullMoons.Count} Full Moons)  ");
        sb.AppendLine(Inv, $"**Lunations near a node:** {series.PossibleEclipses.Count}");
        sb.AppendLine();
        sb.AppendLine("---");
        sb.AppendLine();

        // Lunation timeline table
        sb.AppendLine("## Lunation Timeline");
        sb.AppendLine();
        sb.AppendLine("| # | Date (UTC) | Type | Sign | Degree | Element | Modality | Near a node |");
        sb.AppendLine("|---|------------|------|------|--------|---------|----------|----------|");

        for (int i = 0; i < series.Lunations.Count; i++)
        {
            LunationResult l = series.Lunations[i];
            string eclipse = l.EclipseIndicator ?? "";
            string degFormatted = string.Create(Inv, $"{(int)l.Degree}\u00b0{(int)((l.Degree % 1.0) * 60.0):D2}\u2032");

            sb.AppendLine(
                Inv, $"| {i + 1} | {CalendarDateFormatter.Minutes(l.ExactUtc)} | {l.Type} | " +
                $"{l.Sign} | {degFormatted} | {l.Element} | {l.Modality} | {eclipse} |");
        }

        sb.AppendLine();

        // Eclipse section
        if (series.PossibleEclipses.Count > 0)
        {
            sb.AppendLine("## Lunations near a node");
            sb.AppendLine();
            sb.AppendLine("| Date | Type | Sign | Node Distance | Indicator |");
            sb.AppendLine("|------|------|------|---------------|-----------|");

            foreach (LunationResult l in series.PossibleEclipses)
            {
                string nodeDist = l.NodeDistance.HasValue
                    ? string.Create(Inv, $"{l.NodeDistance.Value:F1}\u00b0")
                    : "\u2014";

                sb.AppendLine(
                    Inv, $"| {CalendarDateFormatter.Date(l.ExactUtc)} | {l.Type} | {l.Sign} | " +
                    $"{nodeDist} | {l.EclipseIndicator} |");
            }

            sb.AppendLine();
        }

        // Footer
        sb.AppendLine("---");
        sb.AppendLine(
            Inv, $"*Generated by {series.EngineVersion} at {series.CalculatedAt:yyyy-MM-dd HH:mm:ss} UTC*");

        return sb.ToString();
    }

    /// <summary>
    /// Format a single lunation chart as Markdown (lunation-specific header + full chart data).
    /// </summary>
    /// <param name="lunation">The lunation result (should have Chart populated).</param>
    /// <returns>A Markdown-formatted lunation chart report.</returns>
    public static string ChartToMarkdown(LunationResult lunation)
    {
        ArgumentNullException.ThrowIfNull(lunation);

        StringBuilder sb = new();

        sb.AppendLine($"# {lunation.Type} in {lunation.Sign}");
        sb.AppendLine();
        sb.AppendLine($"**Date (UTC):** {CalendarDateFormatter.DateTime(lunation.ExactUtc)}  ");
        if (CalendarDateFormatter.IsJulian(lunation.ExactUtc))
            sb.AppendLine(CalendarDateFormatter.JulianCalendarLine + "  ");
        sb.AppendLine($"**Position:** {lunation.PositionFormatted}  ");
        sb.AppendLine($"**Element:** {lunation.Element} | **Modality:** {lunation.Modality}  ");
        sb.AppendLine($"**Sun:** {PositionFormatter.FormatLongitude(lunation.SunLongitude)}  ");
        sb.AppendLine($"**Moon:** {PositionFormatter.FormatLongitude(lunation.MoonLongitude)}  ");
        sb.AppendLine(Inv, $"**Precision:** {lunation.PrecisionArcSeconds:F2} arc-seconds  ");

        if (lunation.IsNearNode)
        {
            sb.AppendLine(Inv, $"**{lunation.EclipseIndicator}** (node distance: {lunation.NodeDistance:F1}\u00b0)  ");
        }

        sb.AppendLine();
        sb.AppendLine("---");
        sb.AppendLine();

        // Never the five minor points (R8)
        if (lunation.Chart is not null)
        {
            sb.Append(ChartMarkdownFormatter.ToMarkdown(lunation.Chart, minorPoints: false));
        }

        return sb.ToString();
    }

    /// <summary>
    /// Save a lunation series report as Markdown to a file.
    /// </summary>
    public static async Task SaveSeriesAsync(
        LunationSeries series, string filePath,
        CancellationToken ct = default)
    {
        string md = SeriesToMarkdown(series);
        await File.WriteAllTextAsync(filePath, md, ct).ConfigureAwait(false);
    }

    /// <summary>
    /// Save a single lunation chart report as Markdown to a file.
    /// </summary>
    public static async Task SaveChartAsync(
        LunationResult lunation, string filePath,
        CancellationToken ct = default)
    {
        string md = ChartToMarkdown(lunation);
        await File.WriteAllTextAsync(filePath, md, ct).ConfigureAwait(false);
    }
}
