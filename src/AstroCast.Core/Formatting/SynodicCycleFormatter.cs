using System.Globalization;
using System.Text;

using AstroCast.Core.Models;

namespace AstroCast.Core.Formatting;

/// <summary>
/// Formats <see cref="SynodicCycleSeries"/> data as Markdown.
/// </summary>
public static class SynodicCycleFormatter
{
    /// <summary>Invariant culture used for all numeric and date formatting.</summary>
    private static readonly CultureInfo Inv = CultureInfo.InvariantCulture;

    /// <summary>
    /// Generate a complete synodic cycle series report as Markdown.
    /// </summary>
    /// <param name="series">The series to format.</param>
    /// <returns>A Markdown-formatted synodic cycle report.</returns>
    public static string ToMarkdown(SynodicCycleSeries series)
    {
        ArgumentNullException.ThrowIfNull(series);

        StringBuilder sb = new();

        // Header
        sb.AppendLine(
            $"# Synodic Cycles: {series.BodyAName}\u2013{series.BodyBName}");
        sb.AppendLine();
        sb.AppendLine(Inv, $"**Generated:** {series.CalculatedAt:yyyy-MM-dd HH:mm:ss} UTC  ");
        sb.AppendLine($"**Software:** {series.EngineVersion}  ");
        sb.AppendLine(Inv, $"**Period:** {series.StartDate.Year} to {series.EndDate.Year}  ");
        if (series.Conjunctions.Count > 0 && CalendarDateFormatter.IsJulian(series.Conjunctions.Min(c => c.DateTimeUtc)))
            sb.AppendLine(CalendarDateFormatter.JulianCalendarLine + "  ");
        sb.AppendLine(Inv, $"**Conjunctions Found:** {series.Count}");

        if (series.AverageSynodicPeriodDays.HasValue)
        {
            sb.AppendLine(
                Inv, $"**Average Synodic Period:** {series.AverageSynodicPeriodDays:F2} days " +
                $"({series.AverageSynodicPeriodYears:F2} years)  ");
            sb.AppendLine(
                Inv, $"**Range:** {series.MinSynodicPeriodDays:F2}\u2013{series.MaxSynodicPeriodDays:F2} days");
        }

        sb.AppendLine();
        sb.AppendLine("---");
        sb.AppendLine();

        // Conjunction timeline table
        if (series.Count > 0)
        {
            sb.AppendLine("## Conjunction Timeline");
            sb.AppendLine();
            sb.AppendLine("| # | Date (UTC) | Position | Sign | Element | Synodic Period |");
            sb.AppendLine("|---|------------|----------|------|---------|---------------|");

            foreach (SynodicConjunction c in series.Conjunctions)
            {
                string period = c.SynodicPeriodDays.HasValue
                    ? string.Create(Inv, $"{c.SynodicPeriodDays:F0} days ({c.SynodicPeriodYears:F2} yr)")
                    : "\u2014";

                // A conjunction of several passes is marked: its first pass carries the period, a
                // later pass has none of its own (T5-2).
                if (c.PassCount > 1)
                {
                    string pass = string.Create(Inv, $"pass {c.PassNumber} of {c.PassCount}");
                    period = c.SynodicPeriodDays.HasValue ? $"{period}, {pass}" : pass;
                }

                sb.AppendLine(
                    Inv, $"| {c.Number} | {CalendarDateFormatter.Date(c.DateTimeUtc)} | {c.Position} | " +
                    $"{c.Sign} | {c.Element} | {period} |");
            }

            sb.AppendLine();
        }

        // Footer
        sb.AppendLine("---");
        sb.AppendLine(
            Inv, $"*Generated by {series.EngineVersion} at {series.CalculatedAt:yyyy-MM-dd HH:mm:ss} UTC*");

        return sb.ToString();
    }

    /// <summary>
    /// Save a synodic cycle series report as Markdown to a file.
    /// </summary>
    /// <param name="series">The series to format.</param>
    /// <param name="filePath">Destination file path for the Markdown output.</param>
    /// <param name="ct">Cancellation token.</param>
    public static async Task SaveSeriesAsync(
        SynodicCycleSeries series, string filePath,
        CancellationToken ct = default)
    {
        string md = ToMarkdown(series);
        await File.WriteAllTextAsync(filePath, md, ct).ConfigureAwait(false);
    }
}
