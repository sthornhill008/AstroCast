using System.Globalization;
using System.Text;

using AstroCast.Core.Models;

namespace AstroCast.Core.Formatting;

/// <summary>
/// Formats <see cref="GreatConjunctionSeries"/> and conjunction chart data as Markdown.
/// </summary>
public static class GreatConjunctionFormatter
{
    /// <summary>Invariant culture used for all numeric and date formatting.</summary>
    private static readonly CultureInfo Inv = CultureInfo.InvariantCulture;

    /// <summary>
    /// Generate a complete great conjunction series report as Markdown.
    /// </summary>
    /// <param name="series">The series to format.</param>
    /// <returns>A Markdown-formatted series report.</returns>
    public static string ToMarkdown(GreatConjunctionSeries series)
    {
        ArgumentNullException.ThrowIfNull(series);

        StringBuilder sb = new();

        sb.AppendLine(
            Inv, $"# Great Conjunctions: {series.ScanStart.Year} \u2013 {series.ScanEnd.Year}");
        sb.AppendLine();
        sb.AppendLine(Inv, $"**Generated:** {series.CalculatedAt:yyyy-MM-dd HH:mm:ss} UTC  ");
        sb.AppendLine($"**Software:** {series.EngineVersion}  ");
        if (series.Conjunctions.Count > 0 && CalendarDateFormatter.IsJulian(series.Conjunctions.Min(c => c.ExactUtc)))
            sb.AppendLine(CalendarDateFormatter.JulianCalendarLine + "  ");
        sb.AppendLine(Inv, $"**Conjunctions Found:** {series.Count}");
        sb.AppendLine();
        sb.AppendLine("---");
        sb.AppendLine();

        // Conjunction timeline table
        sb.AppendLine("## Conjunction Timeline");
        sb.AppendLine();
        sb.AppendLine("| # | Date | Position | Sign | Element | Modality | Mutation | Interval |");
        sb.AppendLine("|---|------|----------|------|---------|----------|----------|----------|");

        for (int i = 0; i < series.Conjunctions.Count; i++)
        {
            GreatConjunctionResult c = series.Conjunctions[i];
            string mutation = c.IsMutation ? "\u2605 MUTATION" : "";
            string interval = c.YearsSincePrevious > 0
                ? string.Create(Inv, $"{c.YearsSincePrevious:F1}y")
                : "\u2014";

            sb.AppendLine(
                Inv, $"| {i + 1} | {CalendarDateFormatter.Date(c.ExactUtc)} | {c.PositionFormatted} | " +
                $"{c.Sign} | {c.Element} | {c.Modality} | {mutation} | {interval} |");
        }

        sb.AppendLine();

        // Footer
        sb.AppendLine("---");
        sb.AppendLine(
            Inv, $"*Generated by {series.EngineVersion} at {series.CalculatedAt:yyyy-MM-dd HH:mm:ss} UTC*");

        return sb.ToString();
    }

    /// <summary>
    /// Generate a conjunction chart report as Markdown, with a conjunction-specific header
    /// prepended to the full chart data.
    /// </summary>
    /// <param name="chart">The chart result at the conjunction moment.</param>
    /// <param name="conjunction">The conjunction metadata.</param>
    /// <returns>A Markdown-formatted conjunction chart report.</returns>
    public static string ChartToMarkdown(ChartResult chart, GreatConjunctionResult conjunction)
    {
        ArgumentNullException.ThrowIfNull(chart);
        ArgumentNullException.ThrowIfNull(conjunction);

        StringBuilder sb = new();

        sb.AppendLine($"# Great Conjunction Chart: {CalendarDateFormatter.Date(conjunction.ExactUtc)}");
        if (CalendarDateFormatter.IsJulian(conjunction.ExactUtc))
            sb.AppendLine(CalendarDateFormatter.JulianCalendarLine + "  ");
        sb.AppendLine();
        sb.AppendLine($"**Position:** {conjunction.PositionFormatted} ({conjunction.Sign})  ");
        sb.AppendLine($"**Element:** {conjunction.Element} | **Modality:** {conjunction.Modality}  ");
        sb.AppendLine(
            $"**Jupiter:** {PositionFormatter.FormatLongitude(conjunction.JupiterLongitude)}  ");
        sb.AppendLine(
            $"**Saturn:** {PositionFormatter.FormatLongitude(conjunction.SaturnLongitude)}  ");
        sb.AppendLine(Inv, $"**Precision:** {conjunction.PrecisionArcSeconds:F2} arc-seconds  ");

        if (conjunction.IsMutation)
            sb.AppendLine("**\u2605 MUTATION:** Element shift from previous conjunction  ");

        sb.AppendLine();
        sb.AppendLine("---");
        sb.AppendLine();

        // Full chart; never the five minor points (R8)
        sb.Append(ChartMarkdownFormatter.ToMarkdown(chart, minorPoints: false));

        return sb.ToString();
    }

    /// <summary>
    /// Save a series report as Markdown to a file.
    /// </summary>
    public static async Task SaveSeriesAsync(
        GreatConjunctionSeries series, string filePath,
        CancellationToken ct = default)
    {
        string md = ToMarkdown(series);
        await File.WriteAllTextAsync(filePath, md, ct).ConfigureAwait(false);
    }

    /// <summary>
    /// Save a conjunction chart report as Markdown to a file.
    /// </summary>
    public static async Task SaveChartAsync(
        ChartResult chart, GreatConjunctionResult conjunction, string filePath,
        CancellationToken ct = default)
    {
        string md = ChartToMarkdown(chart, conjunction);
        await File.WriteAllTextAsync(filePath, md, ct).ConfigureAwait(false);
    }
}
