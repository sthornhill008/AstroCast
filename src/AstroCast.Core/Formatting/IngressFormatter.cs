using System.Globalization;
using System.Text;

using AstroCast.Core.Models;

namespace AstroCast.Core.Formatting;

/// <summary>
/// Formats <see cref="IngressSeries"/> and <see cref="IngressResult"/> data as Markdown.
/// </summary>
public static class IngressFormatter
{
    /// <summary>Invariant culture used for all numeric and date formatting.</summary>
    private static readonly CultureInfo Inv = CultureInfo.InvariantCulture;

    /// <summary>
    /// Format an ingress series as Markdown (timing table only, no full charts).
    /// </summary>
    /// <param name="series">The ingress series to format.</param>
    /// <returns>A Markdown-formatted ingress series report.</returns>
    public static string SeriesToMarkdown(IngressSeries series)
    {
        ArgumentNullException.ThrowIfNull(series);

        StringBuilder sb = new();

        sb.AppendLine(Inv, $"# {series.PlanetName} Ingresses: {series.ScanStart.Year} \u2013 {series.ScanEnd.Year}");
        sb.AppendLine();
        sb.AppendLine(Inv, $"**Generated:** {series.CalculatedAt:yyyy-MM-dd HH:mm:ss} UTC  ");
        sb.AppendLine($"**Software:** {series.EngineVersion}  ");
        if (series.Ingresses.Count > 0 && CalendarDateFormatter.IsJulian(series.Ingresses.Min(r => r.ExactUtc)))
            sb.AppendLine(CalendarDateFormatter.JulianCalendarLine + "  ");
        sb.AppendLine(Inv, $"**Ingresses Found:** {series.Count}");
        sb.AppendLine();
        sb.AppendLine("---");
        sb.AppendLine();

        // Ingress timeline table
        sb.AppendLine("## Ingress Timeline");
        sb.AppendLine();
        sb.AppendLine("| # | Date (UTC) | Planet | Sign | Element | Modality | Season |");
        sb.AppendLine("|---|------------|--------|------|---------|----------|--------|");

        for (int i = 0; i < series.Ingresses.Count; i++)
        {
            IngressResult r = series.Ingresses[i];
            string season = r.SeasonName ?? "\u2014";

            sb.AppendLine(
                Inv, $"| {i + 1} | {CalendarDateFormatter.DateTime(r.ExactUtc)} | {r.PlanetName} | " +
                $"{r.Sign} | {r.Element} | {r.Modality} | {season} |");
        }

        sb.AppendLine();

        // Footer
        sb.AppendLine("---");
        sb.AppendLine(
            Inv, $"*Generated by {series.EngineVersion} at {series.CalculatedAt:yyyy-MM-dd HH:mm:ss} UTC*");

        return sb.ToString();
    }

    /// <summary>
    /// Format a single ingress chart as Markdown (ingress-specific header + full chart data).
    /// </summary>
    /// <param name="ingress">The ingress result (must have Chart populated).</param>
    /// <returns>A Markdown-formatted ingress chart report.</returns>
    public static string ChartToMarkdown(IngressResult ingress)
    {
        ArgumentNullException.ThrowIfNull(ingress);

        StringBuilder sb = new();

        string title = ingress.SeasonName is not null
            ? $"{ingress.PlanetName} Ingress: {ingress.Sign} ({ingress.SeasonName})"
            : $"{ingress.PlanetName} Ingress: {ingress.Sign}";

        sb.AppendLine($"# {title}");
        sb.AppendLine();
        sb.AppendLine($"**Date (UTC):** {CalendarDateFormatter.DateTime(ingress.ExactUtc)}  ");
        if (CalendarDateFormatter.IsJulian(ingress.ExactUtc))
            sb.AppendLine(CalendarDateFormatter.JulianCalendarLine + "  ");
        sb.AppendLine($"**Planet:** {ingress.PlanetName}  ");
        sb.AppendLine($"**Sign:** {ingress.Sign} | **Element:** {ingress.Element} | **Modality:** {ingress.Modality}  ");
        sb.AppendLine(Inv, $"**Target Longitude:** {ingress.TargetLongitude:F1}\u00b0  ");
        sb.AppendLine(Inv, $"**Precision:** {ingress.PrecisionArcSeconds:F2} arc-seconds  ");

        if (ingress.IsCardinalIngress)
            sb.AppendLine($"**Cardinal Ingress:** Yes \u2014 {ingress.SeasonName}  ");

        sb.AppendLine();
        sb.AppendLine("---");
        sb.AppendLine();

        // Full chart if available; never the five minor points (R8)
        if (ingress.Chart is not null)
        {
            sb.Append(ChartMarkdownFormatter.ToMarkdown(ingress.Chart, minorPoints: false));
        }

        return sb.ToString();
    }

    /// <summary>
    /// Format all four cardinal Sun ingresses as a combined Markdown document.
    /// </summary>
    /// <param name="ingresses">The four cardinal ingress results.</param>
    /// <param name="year">The year for the title.</param>
    /// <returns>A Markdown-formatted cardinal ingresses report.</returns>
    public static string CardinalIngressesToMarkdown(
        IReadOnlyList<IngressResult> ingresses, int year)
    {
        ArgumentNullException.ThrowIfNull(ingresses);

        StringBuilder sb = new();

        sb.AppendLine(Inv, $"# Cardinal Sun Ingresses: {year}");
        sb.AppendLine();

        if (ingresses.Count > 0)
        {
            sb.AppendLine(Inv, $"**Generated:** {ingresses[0].CalculatedAt:yyyy-MM-dd HH:mm:ss} UTC  ");
            sb.AppendLine($"**Software:** {ingresses[0].EngineVersion}  ");
            if (CalendarDateFormatter.IsJulian(ingresses.Min(r => r.ExactUtc)))
                sb.AppendLine(CalendarDateFormatter.JulianCalendarLine + "  ");
        }

        sb.AppendLine(Inv, $"**Charts:** {ingresses.Count}");
        sb.AppendLine();

        // Summary table
        sb.AppendLine("## Overview");
        sb.AppendLine();
        sb.AppendLine("| Season | Sign | Date (UTC) | Element | Modality |");
        sb.AppendLine("|--------|------|------------|---------|----------|");

        foreach (IngressResult r in ingresses)
        {
            string season = r.SeasonName ?? r.Sign;
            sb.AppendLine(
                Inv, $"| {season} | {r.Sign} | {CalendarDateFormatter.DateTime(r.ExactUtc)} | " +
                $"{r.Element} | {r.Modality} |");
        }

        sb.AppendLine();
        sb.AppendLine("---");
        sb.AppendLine();

        // Each chart in full
        foreach (IngressResult ingress in ingresses)
        {
            sb.Append(ChartToMarkdown(ingress));
            sb.AppendLine();
            sb.AppendLine("---");
            sb.AppendLine();
        }

        return sb.ToString();
    }

    /// <summary>
    /// Save an ingress series report as Markdown to a file.
    /// </summary>
    /// <param name="series">The series to save.</param>
    /// <param name="filePath">Output file path.</param>
    /// <param name="ct">Cancellation token.</param>
    public static async Task SaveSeriesAsync(
        IngressSeries series, string filePath,
        CancellationToken ct = default)
    {
        string md = SeriesToMarkdown(series);
        await File.WriteAllTextAsync(filePath, md, ct).ConfigureAwait(false);
    }

    /// <summary>
    /// Save a single ingress chart report as Markdown to a file.
    /// </summary>
    /// <param name="ingress">The ingress result to save.</param>
    /// <param name="filePath">Output file path.</param>
    /// <param name="ct">Cancellation token.</param>
    public static async Task SaveChartAsync(
        IngressResult ingress, string filePath,
        CancellationToken ct = default)
    {
        string md = ChartToMarkdown(ingress);
        await File.WriteAllTextAsync(filePath, md, ct).ConfigureAwait(false);
    }

    /// <summary>
    /// Save a cardinal ingresses report as Markdown to a file.
    /// </summary>
    /// <param name="ingresses">The four cardinal ingress results.</param>
    /// <param name="year">The year for the title.</param>
    /// <param name="filePath">Output file path.</param>
    /// <param name="ct">Cancellation token.</param>
    public static async Task SaveCardinalAsync(
        IReadOnlyList<IngressResult> ingresses, int year, string filePath,
        CancellationToken ct = default)
    {
        string md = CardinalIngressesToMarkdown(ingresses, year);
        await File.WriteAllTextAsync(filePath, md, ct).ConfigureAwait(false);
    }
}
