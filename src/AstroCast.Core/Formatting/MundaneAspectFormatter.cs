using System.Globalization;
using System.Text;

using AstroCast.Core.Models;

namespace AstroCast.Core.Formatting;

/// <summary>
/// Formats <see cref="MundaneAspectSeries"/> data as Markdown reports with
/// full UTC date/time precision, cycle phase, and waxing/waning labels
/// for mundane astrology research.
/// </summary>
public static class MundaneAspectFormatter
{
    /// <summary>Invariant culture used for all numeric and date formatting.</summary>
    private static readonly CultureInfo Inv = CultureInfo.InvariantCulture;

    /// <summary>
    /// Generate a complete mundane aspect series report as Markdown.
    /// </summary>
    /// <param name="series">The series to format.</param>
    /// <returns>A Markdown-formatted series report with full date/time precision.</returns>
    public static string ToMarkdown(MundaneAspectSeries series)
    {
        ArgumentNullException.ThrowIfNull(series);

        StringBuilder sb = new();

        sb.AppendLine(
            Inv, $"# Mundane Aspects: {series.Body1Name}\u2013{series.Body2Name} " +
            $"({series.HarmonicMode}), {series.ScanStart.Year}\u2013{series.ScanEnd.Year}");
        sb.AppendLine();
        sb.AppendLine(Inv, $"**Generated:** {series.CalculatedAt:yyyy-MM-dd HH:mm:ss} UTC  ");
        sb.AppendLine($"**Software:** {series.EngineVersion}  ");
        sb.AppendLine($"**Bodies:** {series.Body1Name} and {series.Body2Name}  ");
        sb.AppendLine($"**Mode:** {series.HarmonicMode}  ");
        sb.AppendLine(
            Inv, $"**Period:** {series.ScanStart:yyyy-MM-dd} to {series.ScanEnd:yyyy-MM-dd}  ");
        if (series.Aspects.Count > 0 && CalendarDateFormatter.IsJulian(series.Aspects.Min(a => a.ExactUtc)))
            sb.AppendLine(CalendarDateFormatter.JulianCalendarLine + "  ");
        sb.AppendLine(Inv, $"**Aspects Found:** {series.Count}");
        sb.AppendLine();
        sb.AppendLine("---");
        sb.AppendLine();

        // Aspect timeline table
        sb.AppendLine("## Aspect Timeline");
        sb.AppendLine();
        sb.AppendLine(
            "| # | Date (UTC) | Phase | Aspect | Body 1 | Position 1 | Body 2 | Position 2 | Cycle\u00b0 |");
        sb.AppendLine(
            "|---|------------|-------|--------|--------|------------|--------|------------|--------|");

        for (int i = 0; i < series.Aspects.Count; i++)
        {
            MundaneAspectResult a = series.Aspects[i];
            sb.AppendLine(
                Inv, $"| {i + 1} | {CalendarDateFormatter.DateTime(a.ExactUtc)} | " +
                $"{a.PhaseLabel} | {a.AspectName} | " +
                $"{a.Body1Name} | {a.Position1Formatted} | " +
                $"{a.Body2Name} | {a.Position2Formatted} | " +
                $"{a.CyclePhase:F0}\u00b0 |");
        }

        sb.AppendLine();

        // Footer
        sb.AppendLine("---");
        sb.AppendLine(
            Inv, $"*Generated by {series.EngineVersion} at " +
            $"{series.CalculatedAt:yyyy-MM-dd HH:mm:ss} UTC*");

        return sb.ToString();
    }

    /// <summary>
    /// Save a series report as Markdown to a file.
    /// </summary>
    /// <param name="series">The series to save.</param>
    /// <param name="filePath">The output file path.</param>
    /// <param name="ct">Cancellation token.</param>
    public static async Task SaveAsync(
        MundaneAspectSeries series, string filePath,
        CancellationToken ct = default)
    {
        string md = ToMarkdown(series);
        await File.WriteAllTextAsync(filePath, md, ct).ConfigureAwait(false);
    }
}
