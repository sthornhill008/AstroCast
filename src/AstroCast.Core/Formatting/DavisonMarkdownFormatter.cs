using System.Globalization;
using System.Text;

using AstroCast.Core.Models;

namespace AstroCast.Core.Formatting;

/// <summary>
/// Formats a <see cref="DavisonResult"/> as a Markdown document (branch Davison, 1.7.0): a header naming both
/// charts, the midpoint moment in UT and the midpoint place; the Davison chart's ordinary full report, nothing set
/// aside, since the chart is a real cast; then brief summaries of both source charts, as the composite export
/// prints them. The chart report prints "Davison" as its Type and "UTC+0 (explicit)" as its clock's label; it prints no time
/// lords, as for every chart that is not a Birth chart.
/// </summary>
public static class DavisonMarkdownFormatter
{
    /// <summary>Invariant culture used for all numeric and date formatting.</summary>
    private static readonly CultureInfo Inv = CultureInfo.InvariantCulture;

    /// <summary>
    /// Generate a complete Davison chart report as a Markdown string.
    /// </summary>
    /// <param name="result">The Davison result to format.</param>
    /// <param name="interpretationContext">Optional free-text context for AI interpretation.</param>
    /// <returns>A Markdown-formatted Davison chart report.</returns>
    public static string ToMarkdown(DavisonResult result, string? interpretationContext = null)
    {
        ArgumentNullException.ThrowIfNull(result);

        StringBuilder sb = new();
        ChartResult chart = result.DavisonChart;

        // Section 1: Header. Every line carries the two trailing spaces of a Markdown line break.
        sb.AppendLine($"# Davison Chart: {result.ChartA.Input.Name} & {result.ChartB.Input.Name}");
        sb.AppendLine();
        sb.AppendLine(Inv, $"**Generated:** {result.CalculatedAt:yyyy-MM-dd HH:mm:ss} UTC  ");
        sb.AppendLine($"**Software:** {result.EngineVersion}  ");
        sb.AppendLine(
            "**Method:** Tropical zodiac; the chart cast for the midpoint of the two birth instants (UT) at the midpoint " +
            "of the two birthplaces (the mean latitude, the mean longitude by the shorter arc); " +
            $"{chart.HouseSystemName} houses, Chart A's  ");
        sb.AppendLine(
            Inv, $"**Midpoint Moment:** {CalendarDateFormatter.DateTime(result.MidpointUtc)} UTC (JD {result.MidpointJulianDay:F6})  ");
        if (CalendarDateFormatter.IsJulian(result.MidpointUtc)
            || CalendarDateFormatter.IsJulian(result.ChartA.UtcDateTime)
            || CalendarDateFormatter.IsJulian(result.ChartB.UtcDateTime))
        {
            sb.AppendLine(CalendarDateFormatter.JulianCalendarLine + "  ");
        }

        sb.AppendLine(
            Inv, $"**Midpoint Place:** {result.MidpointLocationDescription} " +
            $"({result.MidpointLatitude:F4}, {result.MidpointLongitude:F4})  ");
        sb.AppendLine($"**Chart A:** {SourceLine(result.ChartA)}  ");
        sb.AppendLine($"**Chart B:** {SourceLine(result.ChartB)}  ");

        if (!string.IsNullOrWhiteSpace(interpretationContext))
        {
            sb.AppendLine($"**Interpretation Context:** {interpretationContext.Trim()}  ");
        }

        sb.AppendLine();
        sb.AppendLine("---");
        sb.AppendLine();

        // Section 2: the Davison chart, the ordinary full report
        sb.AppendLine("## Davison Chart");
        sb.AppendLine();
        sb.Append(FormatChartSection(chart));
        sb.AppendLine();
        sb.AppendLine("---");
        sb.AppendLine();

        // Section 3: Source Chart A summary
        sb.AppendLine($"## Source Chart A: {result.ChartA.Input.Name}");
        sb.AppendLine();
        sb.Append(FormatSourceSummary(result.ChartA));
        sb.AppendLine();
        sb.AppendLine("---");
        sb.AppendLine();

        // Section 4: Source Chart B summary
        sb.AppendLine($"## Source Chart B: {result.ChartB.Input.Name}");
        sb.AppendLine();
        sb.Append(FormatSourceSummary(result.ChartB));
        sb.AppendLine();

        // Footer
        sb.AppendLine("---");
        sb.AppendLine(
            Inv, $"*Generated by {result.EngineVersion} at {result.CalculatedAt:yyyy-MM-dd HH:mm:ss} UTC*");

        return sb.ToString();
    }

    /// <summary>
    /// Save a Davison result as Markdown to a file.
    /// </summary>
    /// <param name="result">The Davison result to save.</param>
    /// <param name="filePath">Destination file path for the Markdown output.</param>
    /// <param name="interpretationContext">Optional free-text context for AI interpretation.</param>
    /// <param name="ct">Cancellation token.</param>
    /// <returns>A task that completes when the file is written.</returns>
    public static async Task SaveAsync(
        DavisonResult result, string filePath,
        string? interpretationContext = null, CancellationToken ct = default)
    {
        string md = ToMarkdown(result, interpretationContext);
        await File.WriteAllTextAsync(filePath, md, ct).ConfigureAwait(false);
    }

    /// <summary>A source chart in one line: its name, its reading as typed with its clock's label, and its place.</summary>
    /// <param name="chart">The source chart.</param>
    /// <returns>The line's text, without the trailing spaces.</returns>
    private static string SourceLine(ChartResult chart) =>
        string.Create(
            Inv,
            $"{chart.Input.Name}, {chart.Input.LocalDateTime:yyyy-MM-dd HH:mm:ss} {ClockLabel(chart)}, {chart.Input.LocationName}");

    /// <summary>
    /// The label of a chart's wall clock: an explicit offset overrides the zone's rules, so the clock is labelled
    /// with that offset, as the chart export's Date/Time line labels it; else the zone in parentheses.
    /// </summary>
    /// <param name="chart">The chart.</param>
    /// <returns>The label.</returns>
    private static string ClockLabel(ChartResult chart) =>
        chart.Input.UseExplicitOffset && chart.Input.UtcOffsetHours.HasValue
            ? chart.ResolvedOffsetLabel
            : $"({chart.Input.TimeZone})";

    /// <summary>
    /// Format the Davison chart body by reusing <see cref="ChartMarkdownFormatter"/> with its defaults (the
    /// temperament, the five when the chart carries them, every section a real chart prints) and stripping the H1
    /// header line and the footer line, as the composite export does.
    /// </summary>
    /// <param name="chart">The Davison chart to format.</param>
    /// <returns>Markdown body without the H1 header or trailing footer.</returns>
    private static string FormatChartSection(ChartResult chart)
    {
        string fullMarkdown = ChartMarkdownFormatter.ToMarkdown(chart);

        // Split into lines and remove:
        // - First line (H1 heading)
        // - Empty line after the heading
        // - Last two lines (footer: "---" and "*Generated by ...*")
        string[] lines = MarkdownLineSplitter.SplitLines(fullMarkdown);

        // Find the first non-empty line after the H1 heading
        int startIndex = 0;
        if (lines.Length > 0 && lines[0].TrimEnd().StartsWith('#'))
            startIndex = 1;

        // Skip blank line after heading
        if (startIndex < lines.Length && string.IsNullOrWhiteSpace(lines[startIndex]))
            startIndex++;

        // Remove footer lines (last "---" and "*Generated by...*")
        int endIndex = lines.Length - 1;
        while (endIndex > startIndex && string.IsNullOrWhiteSpace(lines[endIndex]))
            endIndex--;

        if (endIndex > startIndex && lines[endIndex].TrimEnd().StartsWith("*Generated by"))
            endIndex--;

        if (endIndex > startIndex && lines[endIndex].TrimEnd() == "---")
            endIndex--;

        // Rebuild the body content
        StringBuilder sb = new();
        for (int i = startIndex; i <= endIndex; i++)
        {
            sb.Append(lines[i]);
            if (i < endIndex)
                sb.Append('\n');
        }

        return sb.ToString();
    }

    /// <summary>
    /// Format a brief summary of a source chart showing positions and house cusps only, as the composite export
    /// prints its source charts.
    /// </summary>
    /// <param name="chart">The source chart to summarise.</param>
    /// <returns>Markdown with date/location metadata, positions, and house cusps.</returns>
    private static string FormatSourceSummary(ChartResult chart)
    {
        StringBuilder sb = new();

        sb.AppendLine(
            Inv, $"**Date/Time:** {chart.Input.LocalDateTime:yyyy-MM-dd HH:mm:ss} {ClockLabel(chart)}  ");
        sb.AppendLine(
            Inv, $"**Location:** {chart.Input.LocationName} ({chart.Input.Latitude:F4}, {chart.Input.Longitude:F4})");
        sb.AppendLine();

        // Positions
        sb.AppendLine("### Planetary Positions");
        sb.AppendLine();
        sb.AppendLine("| Body | Position | House | Dir |");
        sb.AppendLine("|------|----------|-------|-----|");

        foreach (PlanetPosition p in chart.Positions)
        {
            string houseStr = p.House.HasValue ? string.Create(Inv, $"{p.House.Value}") : "-";
            sb.AppendLine(
                $"| {p.Name} | {PositionFormatter.FormatPosition(p)} | {houseStr} | {p.DirectionCode} |");
        }

        sb.AppendLine();

        // House Cusps
        sb.AppendLine("### House Cusps");
        sb.AppendLine();
        sb.AppendLine("| House | Cusp |");
        sb.AppendLine("|-------|------|");

        for (int i = 0; i < chart.Houses.Cusps.Count; i++)
        {
            sb.AppendLine(
                Inv, $"| {i + 1} | {PositionFormatter.FormatLongitude(chart.Houses.Cusps[i])} |");
        }

        sb.AppendLine();
        sb.AppendLine($"**ASC:** {PositionFormatter.FormatLongitude(chart.Houses.Ascendant)}  ");
        sb.AppendLine($"**MC:** {PositionFormatter.FormatLongitude(chart.Houses.Midheaven)}");

        return sb.ToString();
    }
}
