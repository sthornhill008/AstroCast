using AstroCast.Core.Enums;
using AstroCast.Core.Formatting;
using AstroCast.Core.Models;

using FluentAssertions;

namespace AstroCast.Tests.Formatting;

/// <summary>
/// Tests that the medical astrology section from <see cref="ChartMarkdownFormatter"/>
/// flows through to the solar return Markdown output via the embedded return chart.
/// </summary>
[Trait("Category", "Unit")]
public sealed class SolarReturnMarkdownMedicalTests
{
    [Fact]
    public void ToMarkdown_SolarReturn_ContainsMedicalSection()
    {
        SolarReturnResult result = CreateTestSolarReturn();
        string md = SolarReturnMarkdownFormatter.ToMarkdown(result);
        md.Should().Contain("## Medical Astrology Correspondences");
    }

    [Fact]
    public void ToMarkdown_SolarReturn_ContainsTemperament()
    {
        SolarReturnResult result = CreateTestSolarReturn();
        string md = SolarReturnMarkdownFormatter.ToMarkdown(result);
        md.Should().Contain("### Temperament");
    }

    [Fact]
    public void ToMarkdown_SolarReturn_ContainsPlanetaryCorrespondences()
    {
        SolarReturnResult result = CreateTestSolarReturn();
        string md = SolarReturnMarkdownFormatter.ToMarkdown(result);
        md.Should().Contain("### Planetary Body Correspondences");
    }

    [Fact]
    public void ToMarkdown_SolarReturn_ContainsHealthHouses()
    {
        SolarReturnResult result = CreateTestSolarReturn();
        string md = SolarReturnMarkdownFormatter.ToMarkdown(result);
        md.Should().Contain("### Health Houses");
    }

    [Fact]
    public void ToMarkdown_SolarReturn_ContainsDisclaimer()
    {
        SolarReturnResult result = CreateTestSolarReturn();
        string md = SolarReturnMarkdownFormatter.ToMarkdown(result);
        md.Should().Contain("Not medical advice");
    }

    [Fact]
    public void ToMarkdown_SolarReturn_MedicalBeforeFooter()
    {
        SolarReturnResult result = CreateTestSolarReturn();
        string md = SolarReturnMarkdownFormatter.ToMarkdown(result);
        int medicalIndex = md.IndexOf("## Medical Astrology Correspondences", StringComparison.Ordinal);
        int footerIndex = md.LastIndexOf("*Generated by", StringComparison.Ordinal);
        medicalIndex.Should().BeLessThan(footerIndex);
    }

    #region Helpers

    private static SolarReturnResult CreateTestSolarReturn()
    {
        ChartResult natal = CreateTestChart();
        ChartResult returnChart = CreateTestChart();

        return new SolarReturnResult
        {
            NatalChart = natal,
            ReturnChart = returnChart,
            Year = 2025,
            NatalSunLongitude = 195.0,
            ReturnSunLongitude = 195.0001,
            ReturnLocationName = "London",
            ReturnLatitude = 51.5,
            ReturnLongitude = -0.1,
            PrecisionArcSeconds = 0.36,
            EngineVersion = "Test 1.0.0",
            CalculatedAt = DateTime.UtcNow,
        };
    }

    private static ChartResult CreateTestChart()
    {
        double ascendant = 215.0;
        return new ChartResult
        {
            Input = new ChartInput
            {
                Name = "Test Subject",
                LocalDateTime = new DateTime(1990, 10, 15, 14, 30, 0),
                TimeZone = "Europe/London",
                Latitude = 51.5,
                Longitude = -0.1,
                LocationName = "London",
            },
            JulianDay = 2448180.0,
            Obliquity = 23.4367,
            UtcDateTime = new DateTime(1990, 10, 15, 13, 30, 0, DateTimeKind.Utc),
            Positions =
            [
                CreatePosition(CelestialBodyId.Sun, 195.0, 10),
                CreatePosition(CelestialBodyId.Moon, 280.0, 2),
                CreatePosition(CelestialBodyId.Mercury, 200.0, 10),
                CreatePosition(CelestialBodyId.Venus, 230.0, 12),
                CreatePosition(CelestialBodyId.Mars, 55.0, 6),
                CreatePosition(CelestialBodyId.Jupiter, 130.0, 9),
                CreatePosition(CelestialBodyId.Saturn, 285.0, 2),
                CreatePosition(CelestialBodyId.Uranus, 280.0, 2),
                CreatePosition(CelestialBodyId.Neptune, 283.0, 2),
                CreatePosition(CelestialBodyId.Pluto, 228.0, 12),
                CreatePosition(CelestialBodyId.TrueNode, 310.0, 3),
                CreatePosition(CelestialBodyId.Chiron, 100.0, 8),
            ],
            Houses = new HouseData
            {
                Cusps = Enumerable.Range(0, 12)
                    .Select(i => (ascendant + i * 30.0) % 360.0).ToList(),
                Ascendant = ascendant,
                Midheaven = (ascendant + 270.0) % 360.0,
                Armc = 0.0,
                Vertex = 0.0,
            },
            Aspects = [],
            Midpoints = [],
            MidpointActivations = [],
            Dignities = [],
            MoonCondition = null,
            ChartContext = null,
            FixedStarConjunctions = [],
            ResolvedUtcOffsetHours = -5.0,
            ResolvedOffsetLabel = "EST (UTC-5)",
            EngineVersion = "Test 1.0.0",
            CalculatedAt = DateTime.UtcNow,
        };
    }

    private static PlanetPosition CreatePosition(CelestialBodyId body, double longitude, int house)
    {
        return new PlanetPosition
        {
            Body = body,
            Name = body.ToString(),
            Longitude = longitude,
            Latitude = 0.0,
            Distance = 1.0,
            SpeedInLongitude = 1.0,
            SpeedInLatitude = 0.0,
            SpeedInDistance = 0.0,
            House = house,
        };
    }

    #endregion
}
