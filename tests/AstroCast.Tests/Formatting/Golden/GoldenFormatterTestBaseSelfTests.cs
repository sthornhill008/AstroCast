using FluentAssertions;

namespace AstroCast.Tests.Formatting.Golden;

/// <summary>
/// Self-tests that verify the normalisation contract of
/// <see cref="GoldenFormatterTestBase"/>. These are the only place the
/// internal <c>Normalise</c> method is exercised directly; the rest of the
/// test suite goes through <c>AssertGolden</c>.
/// </summary>
[Trait("Category", "Unit")]
public sealed class GoldenFormatterTestBaseSelfTests
{
    /// <summary>
    /// Windows CRLF and lone CR line endings must both collapse to LF so that
    /// goldens are byte-identical across Windows and non-Windows file systems.
    /// </summary>
    [Fact]
    public void Normalise_FlattensLineEndingsToLf()
    {
        string input = "alpha\r\nbeta\rgamma\ndelta";

        string result = GoldenFormatterTestBase.Normalise(input);

        result.Should().Be("alpha\nbeta\ngamma\ndelta",
            "CRLF and bare CR must collapse to LF");
    }

    /// <summary>
    /// Engine-version strings such as "AstroCast 1.0.206" move on every patch
    /// release. They must be replaced with a stable placeholder so version
    /// bumps do not churn every golden file.
    /// </summary>
    [Fact]
    public void Normalise_ReplacesEngineVersionToken()
    {
        string input = "Generated by AstroCast 1.0.206 today.";

        string result = GoldenFormatterTestBase.Normalise(input);

        result.Should().Be("Generated by AstroCast X.Y.Z today.",
            "engine version must be replaced with stable placeholder");
    }

    /// <summary>
    /// The SwissEph dependency version string is also version-bumped
    /// independently of AstroCast and must be normalised.
    /// </summary>
    [Fact]
    public void Normalise_ReplacesSwissEphParentheticalVersion()
    {
        string input = "AstroCast 1.0.206 (SwissEph 2.10.03)";

        string result = GoldenFormatterTestBase.Normalise(input);

        result.Should().Be("AstroCast X.Y.Z (SwissEph VER)",
            "Swiss Ephemeris version must be replaced with stable placeholder");
    }

    /// <summary>
    /// The ISO-style UTC stamp on an export's "Generated" lines — the
    /// <c>**Generated:**</c> header and the <c>*Generated by … at …*</c>
    /// footer — is taken at format time (<c>DateTime.UtcNow</c>) and therefore
    /// differs between runs. Both must be replaced with a stable placeholder.
    /// </summary>
    [Fact]
    public void Normalise_ReplacesIsoUtcTimestampToken()
    {
        string input =
            "**Generated:** 2026-04-17 14:23:15 UTC  \n"
            + "*Generated by AstroCast 1.0.206 (SwissEph 2.10.03) at 2026-04-17 14:23:15 UTC*";

        string result = GoldenFormatterTestBase.Normalise(input);

        result.Should().Be(
            "**Generated:** YYYY-MM-DD HH:MM:SS UTC  \n"
            + "*Generated by AstroCast X.Y.Z (SwissEph VER) at YYYY-MM-DD HH:MM:SS UTC*",
            "the Generated header and footer stamps must be replaced with stable placeholders");
    }

    /// <summary>
    /// Event times printed in the same <c>YYYY-MM-DD HH:MM:SS UTC</c> form —
    /// exact transit passes, return instants, a chart's UTC moment — are
    /// computed results, not run-time stamps. They must survive normalisation
    /// so the goldens guard them to the second; masking them once hid a
    /// conversion that printed them up to a second early.
    /// </summary>
    [Fact]
    public void Normalise_LeavesEventUtcTimestampsVisible()
    {
        string input =
            "- **Exact:** 2026-04-15 07:01:20 UTC (orb: 0°00'00\")\n"
            + "**Return Date/Time:** 2026-04-04 14:18:43 UTC  \n"
            + "**UTC Moment:** 2000-01-01 12:00:00 UTC (EST (UTC−5))  ";

        string result = GoldenFormatterTestBase.Normalise(input);

        result.Should().Be(input, "event times are computed results the goldens must guard");
    }

    /// <summary>
    /// The "(as of YYYY-MM-DD)" token emitted by
    /// <c>ChartMarkdownFormatter.AppendProfectionYear</c> embeds
    /// <c>DateTime.Today</c> and therefore drifts by one day every day.
    /// It must be replaced with a stable placeholder so goldens remain
    /// byte-stable across calendar-day boundaries. Root cause F-GR-1,
    /// Session Golden Refresh (v1.0.219).
    /// </summary>
    [Fact]
    public void Normalise_ReplacesAsOfDatePlaceholder_WithFixedToken()
    {
        string input = "**Age:** 26 (as of 2026-04-17)";

        string result = GoldenFormatterTestBase.Normalise(input);

        result.Should().Be("**Age:** 26 (as of YYYY-MM-DD)",
            "profection reference date must be replaced with stable placeholder");
    }

    /// <summary>
    /// Normalisation must be idempotent: running it twice produces the same
    /// result as running it once. This lets test code normalise candidate
    /// output defensively without fear of double-replacement.
    /// </summary>
    [Fact]
    public void Normalise_IsIdempotent()
    {
        string input =
            "AstroCast 1.0.206 (SwissEph 2.10.03)\r\n"
            + "Calculated at 2026-04-17 14:23:15 UTC\r\n"
            + "**Age:** 26 (as of 2026-04-17)\r\n"
            + "Body\r\n";

        string once = GoldenFormatterTestBase.Normalise(input);
        string twice = GoldenFormatterTestBase.Normalise(once);

        twice.Should().Be(once, "Normalise must be idempotent");
    }
}
