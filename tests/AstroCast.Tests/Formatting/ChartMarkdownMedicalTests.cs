using FluentAssertions;

using Serilog;

namespace AstroCast.Tests.Formatting;

/// <summary>
/// Tests for the medical astrology sections embedded in the natal chart
/// Markdown output by <see cref="ChartMarkdownFormatter"/>.
/// </summary>
/// <remarks>
/// The tests that cast a chart through the engine use the shared ephemeris fixture and carry the Integration
/// category as well.
/// </remarks>
[Collection("Ephemeris")]
[Trait("Category", "Unit")]
public sealed class ChartMarkdownMedicalTests
{
    private readonly EphemerisFixture _fixture;

    /// <summary>Receives the shared ephemeris fixture, for the tests that cast a chart through the engine.</summary>
    /// <param name="fixture">The shared ephemeris fixture.</param>
    public ChartMarkdownMedicalTests(EphemerisFixture fixture)
    {
        _fixture = fixture;
    }

    [Fact]
    public void ToMarkdown_ValidChart_ContainsMedicalSection()
    {
        ChartResult chart = CreateTestChart();
        string md = ChartMarkdownFormatter.ToMarkdown(chart);
        md.Should().Contain("## Medical Astrology Correspondences");
    }

    [Fact]
    public void ToMarkdown_ValidChart_ContainsTemperamentSection()
    {
        ChartResult chart = CreateTestChart();
        string md = ChartMarkdownFormatter.ToMarkdown(chart);
        md.Should().Contain("### Temperament");
        md.Should().Contain("Choleric");
        md.Should().Contain("Hot & Dry");
    }

    [Fact]
    public void ToMarkdown_ValidChart_ContainsPlanetaryCorrespondences()
    {
        ChartResult chart = CreateTestChart();
        string md = ChartMarkdownFormatter.ToMarkdown(chart);
        md.Should().Contain("### Planetary Body Correspondences");
        md.Should().Contain("Sun");
        md.Should().Contain("Moon");
    }

    [Fact]
    public void ToMarkdown_ValidChart_ContainsZodiacalAnatomy()
    {
        ChartResult chart = CreateTestChart();
        string md = ChartMarkdownFormatter.ToMarkdown(chart);
        md.Should().Contain("### Zodiacal Anatomy");
        // Should have at least ASC, Sun, Moon signs
        md.Should().Contain("Ascendant");
        md.Should().Contain("Sun sign");
        md.Should().Contain("Moon sign");
    }

    [Fact]
    public void ToMarkdown_ValidChart_ContainsHealthHouses()
    {
        ChartResult chart = CreateTestChart();
        string md = ChartMarkdownFormatter.ToMarkdown(chart);
        md.Should().Contain("### Health Houses");
        md.Should().Contain("6th");
        md.Should().Contain("8th");
        md.Should().Contain("12th");
    }

    [Fact]
    public void ToMarkdown_ValidChart_ContainsDisclaimer()
    {
        ChartResult chart = CreateTestChart();
        string md = ChartMarkdownFormatter.ToMarkdown(chart);
        md.Should().Contain("Not medical advice");
    }

    [Fact]
    public void ToMarkdown_ValidChart_MedicalSectionBeforeFooter()
    {
        ChartResult chart = CreateTestChart();
        string md = ChartMarkdownFormatter.ToMarkdown(chart);
        int medicalIndex = md.IndexOf("## Medical Astrology Correspondences", StringComparison.Ordinal);
        int footerIndex = md.LastIndexOf("*Generated by", StringComparison.Ordinal);
        medicalIndex.Should().BeLessThan(footerIndex);
    }

    [Fact]
    public void ToMarkdown_ValidChart_TrueNodeNotInPlanetaryCorrespondences()
    {
        ChartResult chart = CreateTestChart();
        string md = ChartMarkdownFormatter.ToMarkdown(chart);

        // Find the planetary correspondences table section
        int tableStart = md.IndexOf("### Planetary Body Correspondences", StringComparison.Ordinal);
        int tableEnd = md.IndexOf("### Zodiacal Anatomy", StringComparison.Ordinal);
        string tableSection = md[tableStart..tableEnd];

        tableSection.Should().NotContain("TrueNode");
        tableSection.Should().NotContain("Chiron");
    }

    /// <summary>
    /// The Temperament block's scoring line names the scheme as AstroCast's own and says which bodies count as
    /// angular: each of the twelve in houses 1, 4, 7 or 10 (ruling S-D9; Y5-2, Y5-3).
    /// </summary>
    [Fact]
    public void ToMarkdown_ScoringLine_NamesTheAppsOwnScheme()
    {
        List<string> lines = Lines(ChartMarkdownFormatter.ToMarkdown(CreateTestChart()));

        lines.Should().Contain(
            "Scoring (AstroCast's own scheme): ASC sign 3pts, ASC ruler sign 2pts, Moon sign 3pts, Moon dispositor sign 2pts, Sun sign 1pt, each body in houses 1, 4, 7 or 10 1pt.");
    }

    /// <summary>
    /// Person A (JD UT 2432464.1041666665, 40.2737 N 76.8844 W, Placidus), cast through the engine, scores
    /// Fire 2, Earth 1, Air 5, Water 6 (Tier A: the scheme counted on Swiss Ephemeris positions and houses computed
    /// outside AstroCast, houses by longitude; fixtures/truth/medical_scores.py). The Ascendant in Scorpio (3) and
    /// its dispositor chain go to Water: the Moon's dispositor Mercury in Scorpio (2) and Jupiter in the 1st (1);
    /// the Ascendant's ruler Mars in Leo (2) to Fire; the Moon in Gemini (3), the Sun in Libra (1) and the angular
    /// Moon in the 7th (1) to Air; the True Node in the 7th (1), in Taurus, to Earth. No two elements tie for
    /// first here: a real-chart tie needs a chart none of the suite's fixtures provides, so the tie's printing is
    /// held by <c>MedicalMarkdownFormatterTests.Format_DominantTie_PrintsTheTie</c> on hand-set scores, and this
    /// end-to-end case pins the untied line.
    /// </summary>
    [Fact]
    [Trait("Category", "Integration")]
    public void ToMarkdown_Hartwell_PrintsTheDominantAndSecondary()
    {
        ChartResult chart = GoldenFixtures.CreateChartEngine(_fixture).Calculate(HartwellInput());

        List<string> lines = Lines(ChartMarkdownFormatter.ToMarkdown(chart));

        chart.JulianDay.Should().BeApproximately(2432464.1041666665, 1e-8);
        lines.Should().Contain("**Dominant:** Phlegmatic | **Secondary:** Sanguine");
    }

    /// <summary>
    /// With <c>includeTemperament: false</c> the J2000 NYC chart prints no Temperament block, and the rest of its
    /// Medical Astrology Correspondences section stays (ruling S-D9: a derived chart prints no temperament).
    /// </summary>
    [Fact]
    [Trait("Category", "Integration")]
    public void ToMarkdown_WithoutTemperament_KeepsTheOtherMedicalTables()
    {
        ChartResult chart = GoldenFixtures.J2000Nyc(_fixture);

        List<string> lines = Lines(ChartMarkdownFormatter.ToMarkdown(chart, includeTemperament: false));

        lines.Should().NotContain("### Temperament");
        lines.Should().Contain("## Medical Astrology Correspondences");
        lines.Should().Contain("### Planetary Body Correspondences");
        lines.Should().Contain("### Health Houses");
    }

    /// <summary>
    /// The relocation export of its golden test (J2000 NYC relocated to Los Angeles) prints no Temperament block for
    /// the relocated chart and keeps its Planetary Body Correspondences (ruling S-D9).
    /// </summary>
    [Fact]
    [Trait("Category", "Integration")]
    public void Relocation_HasNoTemperament()
    {
        ChartResult natal = GoldenFixtures.J2000Nyc(_fixture);
        RelocationResult result = new RelocationService(
                GoldenFixtures.CreateChartEngine(_fixture), new LoggerConfiguration().CreateLogger())
            .Calculate(natal, new RelocationInput { Latitude = 34.0522, Longitude = -118.2437, LocationName = "Los Angeles" });

        List<string> lines = Lines(RelocationMarkdownFormatter.ToMarkdown(result, GoldenFixtures.GoldenClock()));

        lines.Should().NotContain("### Temperament");
        lines.Should().Contain("### Planetary Body Correspondences");
    }

    /// <summary>
    /// The composite export of its golden test (J2000 NYC and the secondary natal) prints no Temperament block for
    /// the composite chart and keeps its Planetary Body Correspondences (ruling S-D9).
    /// </summary>
    [Fact]
    [Trait("Category", "Integration")]
    public void Composite_HasNoTemperament()
    {
        ILogger logger = new LoggerConfiguration().CreateLogger();
        DignityService dignity = new();
        CompositeService service = new(
            _fixture.EphemerisService,
            new AspectService(_fixture.EphemerisService, logger),
            new MidpointService(logger),
            dignity,
            new MoonConditionService(),
            new ChartContextService(dignity, new SectService()),
            new FixedStarService(_fixture.EphemerisService, logger),
            logger);
        CompositeResult result = service.Calculate(GoldenFixtures.J2000Nyc(_fixture), GoldenFixtures.SecondaryNatal(_fixture));

        List<string> lines = Lines(CompositeMarkdownFormatter.ToMarkdown(result));

        lines.Should().NotContain("### Temperament");
        lines.Should().Contain("### Planetary Body Correspondences");
    }

    /// <summary>
    /// The electional export of its golden test (J2000 NYC, a business launch in New York, 20 to 25 April 2026, three
    /// candidates) prints no Temperament block for any candidate chart and keeps their Planetary Body
    /// Correspondences (ruling S-D9).
    /// </summary>
    [Fact]
    [Trait("Category", "Integration")]
    public void Electional_CandidatesHaveNoTemperament()
    {
        ElectionalResult result = new ElectionalService(_fixture.EphemerisService, GoldenFixtures.CreateChartEngine(_fixture))
            .Calculate(new ElectionalInput
            {
                NatalChart = GoldenFixtures.J2000Nyc(_fixture),
                ElectionType = ElectionType.BusinessLaunch,
                ElectionGoal = "Launch a new software product.",
                RangeStart = new DateOnly(2026, 4, 20),
                RangeEnd = new DateOnly(2026, 4, 25),
                Latitude = 40.7128,
                Longitude = -74.006,
                LocationName = "New York City",
                TimeZone = "America/New_York",
                CandidateCount = 3,
            });

        List<string> lines = Lines(ElectionalMarkdownFormatter.ToMarkdown(result));

        result.Candidates.Should().HaveCount(3);
        lines.Should().NotContain("### Temperament");
        lines.Should().Contain("### Planetary Body Correspondences");
    }

    #region Helpers

    /// <summary>
    /// Person A's input (invented): 1947-10-05 09:30:00 at an explicit UTC−5, Harrisburg, Pennsylvania, Placidus.
    /// </summary>
    /// <returns>A new <see cref="ChartInput"/> for person A.</returns>
    private static ChartInput HartwellInput() => new()
    {
        Name = "Eleanor Hartwell",
        LocalDateTime = new DateTime(1947, 10, 5, 9, 30, 0),
        TimeZone = "America/New_York",
        UtcOffsetHours = -5.0,
        UseExplicitOffset = true,
        Latitude = 40.2737,
        Longitude = -76.8844,
        LocationName = "Harrisburg, Pennsylvania",
        EventType = "Birth",
        HouseSystem = HouseSystem.Placidus,
    };

    /// <summary>The export's lines, each without its line terminator.</summary>
    /// <param name="markdown">A Markdown export.</param>
    /// <returns>The export's lines, in order.</returns>
    private static List<string> Lines(string markdown) => [.. markdown.Split('\n').Select(l => l.TrimEnd('\r'))];

    private static ChartResult CreateTestChart()
    {
        // Sun in Libra (195°), Moon in Capricorn (280°), ASC in Scorpio (215°)
        double ascendant = 215.0;
        return new ChartResult
        {
            Input = new ChartInput
            {
                Name = "Test Subject",
                LocalDateTime = new DateTime(1990, 10, 15, 14, 30, 0),
                TimeZone = "Europe/London",
                Latitude = 51.5,
                Longitude = -0.1,
                LocationName = "London"
            },
            JulianDay = 2448180.0,
            Obliquity = 23.4367,
            UtcDateTime = new DateTime(1990, 10, 15, 13, 30, 0, DateTimeKind.Utc),
            Positions =
            [
                CreatePosition(CelestialBodyId.Sun, 195.0, 10),       // Libra
                CreatePosition(CelestialBodyId.Moon, 280.0, 2),       // Capricorn
                CreatePosition(CelestialBodyId.Mercury, 200.0, 10),   // Libra
                CreatePosition(CelestialBodyId.Venus, 230.0, 12),     // Scorpio
                CreatePosition(CelestialBodyId.Mars, 55.0, 6),        // Taurus
                CreatePosition(CelestialBodyId.Jupiter, 130.0, 9),    // Leo
                CreatePosition(CelestialBodyId.Saturn, 285.0, 2),     // Capricorn
                CreatePosition(CelestialBodyId.Uranus, 280.0, 2),     // Capricorn
                CreatePosition(CelestialBodyId.Neptune, 283.0, 2),    // Capricorn
                CreatePosition(CelestialBodyId.Pluto, 228.0, 12),     // Scorpio
                CreatePosition(CelestialBodyId.TrueNode, 310.0, 3),   // Aquarius
                CreatePosition(CelestialBodyId.Chiron, 100.0, 8),     // Cancer
            ],
            Houses = new HouseData
            {
                Cusps = Enumerable.Range(0, 12)
                    .Select(i => (ascendant + i * 30.0) % 360.0).ToList(),
                Ascendant = ascendant,
                Midheaven = (ascendant + 270.0) % 360.0,
                Armc = 0.0,
                Vertex = 0.0,
            },
            Aspects = [],
            Midpoints = [],
            MidpointActivations = [],
            Dignities = [],
            MoonCondition = null,
            ChartContext = null,
            FixedStarConjunctions = [],
            ResolvedUtcOffsetHours = -5.0,
            ResolvedOffsetLabel = "EST (UTC-5)",
            EngineVersion = "Test 1.0.0",
            CalculatedAt = DateTime.UtcNow,
        };
    }

    private static PlanetPosition CreatePosition(CelestialBodyId body, double longitude, int house)
    {
        return new PlanetPosition
        {
            Body = body,
            Name = body.ToString(),
            Longitude = longitude,
            Latitude = 0.0,
            Distance = 1.0,
            SpeedInLongitude = 1.0,
            SpeedInLatitude = 0.0,
            SpeedInDistance = 0.0,
            House = house,
        };
    }

    #endregion
}
