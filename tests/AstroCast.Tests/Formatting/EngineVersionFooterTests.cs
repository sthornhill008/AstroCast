using System.Text.RegularExpressions;

using AstroCast.Core.Enums;
using AstroCast.Core.Formatting;
using AstroCast.Core.Models;
using AstroCast.Core.Models.Astrocartography;
using AstroCast.Core.Models.Electional;
using AstroCast.Core.Models.Transit;
using AstroCast.Core.Services;

using AstroCast.Tests.Fixtures;
using AstroCast.Tests.Formatting.Golden;

using FluentAssertions;

using Serilog;

namespace AstroCast.Tests.Formatting;

/// <summary>
/// E2-9 (branch O-4): the astrocartography and electional exports print the engine version in
/// their footers, as the chart export prints it — "AstroCast 1.3.3 (SwissEph 2.10.03, tzdb
/// 2026e)" — so a file on disk can be dated to the version that made it. Neither export's
/// "Generated" stamp changes.
/// </summary>
/// <remarks>
/// The reference is the chart export itself (fidelity): the version in the new footer must be
/// the one the chart export's <c>*Generated by … at …*</c> footer prints for the same natal
/// chart.
/// </remarks>
[Collection("Ephemeris")]
[Trait("Category", "Integration")]
public sealed class EngineVersionFooterTests
{
    /// <summary>The chart export's footer, from which the reference version is read.</summary>
    private static readonly Regex ChartFooter = new(@"^\*Generated by (.+) at \d{4}-\d{2}-\d{2} \d{2}:\d{2}:\d{2} UTC\*$", RegexOptions.Multiline);

    private readonly EphemerisFixture _fixture;
    private readonly ILogger _logger;

    /// <summary>
    /// Receives the shared ephemeris fixture used by every test in this class.
    /// </summary>
    /// <param name="fixture">xUnit-injected shared ephemeris fixture.</param>
    public EngineVersionFooterTests(EphemerisFixture fixture)
    {
        _fixture = fixture;
        _logger = new LoggerConfiguration().CreateLogger();
    }

    /// <summary>
    /// The astrocartography export ends with the engine version the chart export prints, after
    /// its data footer, and keeps its Generated header.
    /// </summary>
    [Fact]
    public void Astrocartography_Footer_PrintsTheEngineVersion_AsTheChartExportDoes()
    {
        ChartResult natal = GoldenFixtures.J2000Nyc(_fixture);
        AcgResult acg = new AstrocartographyService(_fixture.EphemerisService, _logger).Calculate(natal);

        string[] lines = Lines(AstrocartographyFormatter.ToMarkdown(acg));

        string version = ChartExportVersion(natal);
        lines[^1].Should().Be($"*Engine: {version}*");
        lines[^2].Should().BeEmpty();
        lines[^3].Should().StartWith("*Data from AstroCast (Swiss Ephemeris). Lines in mundo:");
        lines.Should().ContainSingle(l => l.StartsWith("**Generated:** ", StringComparison.Ordinal));
    }

    /// <summary>
    /// The electional export ends with a footer carrying the engine version the chart export
    /// prints, after its void-of-course calendar, and keeps its Generated and Software lines.
    /// </summary>
    [Fact]
    public void Electional_Footer_PrintsTheEngineVersion_AsTheChartExportDoes()
    {
        ChartResult natal = GoldenFixtures.J2000Nyc(_fixture);
        ElectionalResult result = new ElectionalService(_fixture.EphemerisService, GoldenFixtures.CreateChartEngine(_fixture))
            .Calculate(new ElectionalInput
            {
                NatalChart = natal,
                ElectionType = ElectionType.Other,
                ElectionGoal = "Engine version sample",
                RangeStart = new DateOnly(2026, 10, 5),
                RangeEnd = new DateOnly(2026, 10, 6),
                Latitude = 40.7128,
                Longitude = -74.006,
                LocationName = "New York City",
                TimeZone = "America/New_York",
                CandidateCount = 1,
            });

        string[] lines = Lines(ElectionalMarkdownFormatter.ToMarkdown(result));

        string version = ChartExportVersion(natal);
        lines[^1].Should().Be($"*Engine: {version}*");
        lines[^2].Should().Be("---");
        lines.Should().ContainSingle(l => l.StartsWith("**Generated:** ", StringComparison.Ordinal));
        lines.Should().ContainSingle(l => l == "**Software:** AstroCast — Swiss Ephemeris, Tropical, Placidus");
    }

    /// <summary>
    /// The transit export ends with a rule and the engine version the chart export prints, and
    /// keeps its Generated and Software lines (E2-9, branch O-2). With progressions it ends with
    /// the Solar Arcs table, as the golden does, so the rule is added; without them the last
    /// section closes with its own rule, and exactly one rule still stands before the engine line.
    /// </summary>
    [Fact]
    public void Transit_Footer_PrintsTheEngineVersion_AsTheChartExportDoes()
    {
        ChartResult natal = GoldenFixtures.J2000Nyc(_fixture);
        TransitResult result = Transits(natal, includeProgressions: true);

        string[] lines = Lines(TransitMarkdownFormatter.ToMarkdown(result));

        string version = ChartExportVersion(natal);
        lines[^1].Should().Be($"*Engine: {version}*");
        lines[^2].Should().Be("---");
        lines.Should().ContainSingle(l => l.StartsWith("**Generated:** ", StringComparison.Ordinal));
        lines.Should().ContainSingle(l => l == "**Software:** AstroCast — Swiss Ephemeris, Tropical, Placidus");

        string[] closed = Lines(TransitMarkdownFormatter.ToMarkdown(Transits(natal)));
        closed[^1].Should().Be($"*Engine: {version}*");
        Enumerable.Reverse(closed).Skip(1).TakeWhile(l => l.Length == 0 || l == "---").Count(l => l == "---")
            .Should().Be(1, "exactly one rule stands before the engine line");
    }

    /// <summary>
    /// The transit-timeline export ends with the engine version the chart export prints, after
    /// its data footer (E2-9, branch O-2).
    /// </summary>
    [Fact]
    public void TransitTimeline_Footer_PrintsTheEngineVersion_AsTheChartExportDoes()
    {
        ChartResult natal = GoldenFixtures.J2000Nyc(_fixture);
        TransitResult result = Transits(natal);

        string[] lines = Lines(TransitTimelineMarkdownFormatter.ToMarkdown(result));

        string version = ChartExportVersion(natal);
        lines[^1].Should().Be($"*Engine: {version}*");
        lines[^2].Should().BeEmpty();
        lines[^3].Should().StartWith("*Data from AstroCast (Swiss Ephemeris, Tropical, Placidus).");
    }

    /// <summary>
    /// The daily horoscope ends with the engine version the chart export prints, after the last
    /// day's closing rule, and keeps its Generated and Software lines (E2-9, branch O-2).
    /// </summary>
    [Fact]
    public void DailyHoroscope_Footer_PrintsTheEngineVersion_AsTheChartExportDoes()
    {
        ChartResult natal = GoldenFixtures.J2000Nyc(_fixture);
        TransitResult result = Transits(natal);
        string zone = natal.Input.TimeZone;
        IReadOnlyList<DailyHoroscopeDay> days = new DailyHoroscopeService(_fixture.EphemerisService).BuildDays(result, zone);

        string[] lines = Lines(DailyHoroscopeMarkdownFormatter.ToMarkdown(result, days, null, null, zone));

        string version = ChartExportVersion(natal);
        days.Should().NotBeEmpty();
        lines[^1].Should().Be($"*Engine: {version}*");
        lines[^2].Should().BeEmpty();
        lines[^3].Should().Be("---");
        lines.Should().ContainSingle(l => l.StartsWith("**Generated:** ", StringComparison.Ordinal));
        lines.Should().ContainSingle(l => l == "**Software:** AstroCast — Swiss Ephemeris, Tropical, Placidus");
    }

    /// <summary>
    /// The transits to <paramref name="natal"/> over 5 to 7 October 2026, major aspects, without
    /// progressions unless asked for.
    /// </summary>
    /// <param name="natal">The natal chart.</param>
    /// <param name="includeProgressions">Whether to include progressions and solar arcs.</param>
    /// <returns>The transit result.</returns>
    private TransitResult Transits(ChartResult natal, bool includeProgressions = false) =>
        new TransitService(_fixture.EphemerisService, _logger).Calculate(new TransitInput
        {
            NatalChart = natal,
            ReportStartDate = new DateOnly(2026, 10, 5),
            ReportEndDate = new DateOnly(2026, 10, 7),
            IncludeMinorAspects = false,
            IncludeSolarArcs = includeProgressions,
            IncludeSecondaryProgressions = includeProgressions,
        });

    /// <summary>
    /// The engine version the chart export prints for <paramref name="natal"/>, read from its
    /// <c>*Generated by … at …*</c> footer; it names the ephemeris and the zone data.
    /// </summary>
    private static string ChartExportVersion(ChartResult natal)
    {
        Match m = ChartFooter.Match(ChartMarkdownFormatter.ToMarkdown(natal).Replace("\r", "", StringComparison.Ordinal));
        m.Success.Should().BeTrue("the chart export ends with its Generated-by footer");
        string version = m.Groups[1].Value;
        version.Should().MatchRegex(@"^AstroCast \d+\.\d+\.\d+ \(SwissEph [^,()]+, tzdb \d{4}[a-z]\)$");
        return version;
    }

    /// <summary>
    /// The export's lines, without a final empty line after its last newline, and without a line's trailing
    /// spaces: a header line that another follows ends with two, a hard break (branch ExportText, 1.7.2).
    /// </summary>
    private static string[] Lines(string md) =>
        [.. md.Replace("\r", "", StringComparison.Ordinal).TrimEnd('\n').Split('\n').Select(l => l.TrimEnd(' '))];
}
