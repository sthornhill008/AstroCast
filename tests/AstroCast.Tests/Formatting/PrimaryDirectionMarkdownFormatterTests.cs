using AstroCast.Core.Formatting;
using AstroCast.Core.Models;
using AstroCast.Core.Models.PrimaryDirections;
using AstroCast.Core.Services.PrimaryDirections;

using AstroCast.Tests.Fixtures;
using AstroCast.Tests.Formatting.Golden;

using FluentAssertions;

namespace AstroCast.Tests.Formatting;

/// <summary>
/// <see cref="PrimaryDirectionMarkdownFormatter"/> (branch PrimaryExport, 1.5.0): the whole-life report's
/// header, its embedded natal chart, its section and its footer, on real charts.
/// </summary>
/// <param name="fixture">The shared ephemeris fixture.</param>
[Collection("Ephemeris")]
[Trait("Category", "Integration")]
public sealed class PrimaryDirectionMarkdownFormatterTests(EphemerisFixture fixture)
{
    /// <summary>The header's lines, in order, for a chart without a birth-time source.</summary>
    [Fact]
    public void Header_PrintsTheLinesInOrder()
    {
        List<string> lines = Lines(ToMarkdown(GoldenFixtures.J2000NycInput()));

        lines[0].Should().Be("# Primary Directions Report");
        lines[1].Should().BeEmpty();
        lines[2].Should().Be("**Name:** J2000 NYC Fixture");
        lines[3].Should().Be("**Natal Date:** 2000-01-01, 07:00:00 America/New_York, New York City");
        lines[4].Should().Be("**Birth Time Source:** Not specified");
        lines[5].Should().Be("**Span:** birth to age 100");
        lines[6].Should().Be("**Techniques:** Primary Directions");
        lines[7].Should().StartWith("**Generated:** ").And.EndWith(" UTC");
        lines[8].Should().Be("**Software:** AstroCast — Swiss Ephemeris, Tropical, Placidus");
        lines[9].Should().BeEmpty();
        lines[10].Should().Be("---");
    }

    /// <summary>The Birth Time Source comes from the chart's own source notes, and the section then has no caution.</summary>
    [Fact]
    public void Header_WithSource_PrintsItFromTheChart()
    {
        List<string> lines = Lines(ToMarkdown(GoldenFixtures.HartwellInput("Birth Certificate")));

        lines[4].Should().Be("**Birth Time Source:** Birth Certificate");
        lines[3].Should().StartWith("**Natal Date:** 1947-10-05, 09:30:00 ").And.EndWith(", Harrisburg, Pennsylvania");
        lines.Should().NotContain(l => l.StartsWith("**Birth time:**", StringComparison.Ordinal));
    }

    /// <summary>The Span line and the sub-heading follow the age limit.</summary>
    [Fact]
    public void Span_FollowsTheAgeLimit()
    {
        List<string> lines = Lines(ToMarkdown(GoldenFixtures.J2000NycInput(), new PrimaryDirectionSettings { AgeLimitYears = 80 }));

        lines.Should().Contain("**Span:** birth to age 80");
        lines.Should().Contain("### Primary Directions, Birth to Age 80");
    }

    /// <summary>A result without a hit prints the none sentence in the table's place.</summary>
    [Fact]
    public void NoHits_PrintsTheNoneSentence()
    {
        PrimaryDirectionResult result = Calculate(GoldenFixtures.J2000NycInput(), PrimaryDirectionSettings.Default);
        PrimaryDirectionResult empty = new()
        {
            NatalChart = result.NatalChart,
            Settings = result.Settings,
            Hits = [],
            LeftOutCount = result.LeftOutCount,
        };

        List<string> lines = Lines(PrimaryDirectionMarkdownFormatter.ToMarkdown(empty, GoldenFixtures.GoldenClock()));

        lines.Should().Contain("No primary direction falls before age 100.");
        lines.Should().NotContain(l => l.StartsWith("| Date (UTC)", StringComparison.Ordinal));
    }

    /// <summary>The natal chart is embedded without its own title and footer, as the transit report embeds it.</summary>
    [Fact]
    public void EmbedsTheNatalChart()
    {
        List<string> lines = Lines(ToMarkdown(GoldenFixtures.J2000NycInput()));

        lines.Should().Contain("## Natal Chart");
        lines.Should().Contain("## Planetary Positions");
        lines.Count(l => l.StartsWith("# ", StringComparison.Ordinal)).Should().Be(1, "the natal chart's title is stripped");
        lines.Count(l => l.StartsWith("*Generated by", StringComparison.Ordinal)).Should().Be(0, "the natal chart's footer is stripped");
        lines.IndexOf("## Natal Chart").Should().BeLessThan(lines.IndexOf("## Primary Directions"));
    }

    /// <summary>The document ends with a rule and the engine line.</summary>
    [Fact]
    public void EndsWithTheEngineFooter()
    {
        string markdown = ToMarkdown(GoldenFixtures.J2000NycInput());
        List<string> lines = Lines(markdown.TrimEnd('\r', '\n'));

        lines[^2].Should().Be("---");
        lines[^1].Should().StartWith("*Engine: AstroCast ").And.EndWith("*");
        lines.Count(l => l.StartsWith("*Engine:", StringComparison.Ordinal)).Should().Be(1);
    }

    /// <summary>A natal chart before 1582-10-15 prints the Calendar line after the Span line, and its dates on the Julian calendar.</summary>
    [Fact]
    public void JulianNatal_PrintsTheCalendarLine()
    {
        List<string> lines = Lines(ToMarkdown(GoldenFixtures.N1Input()));

        lines[5].Should().Be("**Span:** birth to age 100");
        lines[6].Should().Be("**Calendar:** dates before 1582-10-15 are on the Julian calendar");
        lines[7].Should().Be("**Techniques:** Primary Directions");
        lines.Should().Contain(l => l.StartsWith("| 1300-04-18 | 0.09 | D | Sun | cnj | Difda |", StringComparison.Ordinal));
    }

    /// <summary>SaveAsync writes the document to the file.</summary>
    [Fact]
    public async Task SaveAsync_WritesTheMarkdown()
    {
        PrimaryDirectionResult result = Calculate(GoldenFixtures.J2000NycInput(), PrimaryDirectionSettings.Default);
        string path = Path.Combine(Path.GetTempPath(), $"astrocast-pd-{Guid.NewGuid():N}.md");
        try
        {
            await PrimaryDirectionMarkdownFormatter.SaveAsync(result, path);

            string written = await File.ReadAllTextAsync(path);
            written.Should().StartWith("# Primary Directions Report");
            written.Should().Contain("## Primary Directions");
        }
        finally
        {
            File.Delete(path);
        }
    }

    /// <summary>
    /// The table the Directions panel lists is the report's own (branch PrimaryPanel, 1.5.0): the report holds it
    /// whole, and at an uncertainty of 4 minutes its first line is the header with the Range column.
    /// </summary>
    [Fact]
    public void FormatTable_IsTheReportsTable()
    {
        PrimaryDirectionResult result = Calculate(
            GoldenFixtures.J2000NycInput(), new PrimaryDirectionSettings { BirthTimeUncertaintyMinutes = 4 });

        string table = PrimaryDirectionMarkdownFormatter.FormatTable(result);
        string report = PrimaryDirectionMarkdownFormatter.ToMarkdown(result, GoldenFixtures.GoldenClock());

        report.Should().Contain(table);
        List<string> lines = Lines(table.TrimEnd('\r', '\n'));
        lines[0].Should().Be("| Date (UTC) | Age | D/C | Significator | Aspect | Promissor | Arc | Months/min | Range (\u00b14 min) |");
        lines.Should().HaveCount(result.Hits.Count + 2, "the header, the separator and one row per hit");
    }

    /// <summary>Without a hit the table is the report's none sentence.</summary>
    [Fact]
    public void FormatTable_NoHits_IsTheNoneSentence()
    {
        PrimaryDirectionResult result = Calculate(GoldenFixtures.J2000NycInput(), PrimaryDirectionSettings.Default);
        PrimaryDirectionResult empty = new()
        {
            NatalChart = result.NatalChart,
            Settings = new PrimaryDirectionSettings { AgeLimitYears = 80 },
            Hits = [],
            LeftOutCount = result.LeftOutCount,
        };

        PrimaryDirectionMarkdownFormatter.FormatTable(empty)
            .Should().Be("No primary direction falls before age 80." + Environment.NewLine);
    }

    #region Helpers

    /// <summary>The report for a chart under settings, with the golden clock.</summary>
    private string ToMarkdown(ChartInput input, PrimaryDirectionSettings? settings = null) =>
        PrimaryDirectionMarkdownFormatter.ToMarkdown(Calculate(input, settings ?? PrimaryDirectionSettings.Default), GoldenFixtures.GoldenClock());

    /// <summary>A chart's directions under settings.</summary>
    private PrimaryDirectionResult Calculate(ChartInput input, PrimaryDirectionSettings settings)
    {
        ChartResult chart = GoldenFixtures.CreateChartEngine(fixture).Calculate(input);
        return new PrimaryDirectionService(fixture.EphemerisService).Calculate(chart, settings);
    }

    /// <summary>The document's lines without their terminators.</summary>
    private static List<string> Lines(string markdown) => [.. markdown.Split('\n').Select(l => l.TrimEnd('\r', ' '))];

    #endregion

    #region Hard breaks (branch ExportText, 1.7.2)

    /// <summary>
    /// The report's header lines each end with two spaces, Markdown's hard break, but the last, Software
    /// (finding A3). Until 1.7.2 none did, so a Markdown reader ran the header into one paragraph.
    /// </summary>
    [Fact]
    public void Header_BreaksEveryLineButTheLast()
    {
        string[] lines = [.. ToMarkdown(GoldenFixtures.HartwellInput("Birth Certificate")).Split('\n').Select(l => l.TrimEnd('\r'))];

        string[] header = [.. lines.Skip(2).TakeWhile(l => l.Length > 0)];

        header.Should().Contain("**Name:** Eleanor Hartwell  ")
            .And.Contain("**Birth Time Source:** Birth Certificate  ")
            .And.Contain("**Span:** birth to age 100  ")
            .And.Contain("**Techniques:** Primary Directions  ");
        header[..^1].Should().OnlyContain(l => l.EndsWith("  ", StringComparison.Ordinal));
        header[^1].Should().StartWith("**Software:**").And.NotEndWith(" ");
    }

    #endregion
}
